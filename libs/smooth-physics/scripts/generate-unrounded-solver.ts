// Generates src/solver-unrounded.ts, the kernels of 'default' precision, from src/solver.ts by removing every Float32
// rounding call. The result runs the same steps in JavaScript doubles: faster, and not bit-exact with 'rounded'.
// Usage: vpx scripts/generate-unrounded-solver.ts [--check]
import { readFileSync, writeFileSync } from 'node:fs';

const solverUrl = new URL('../src/solver.ts', import.meta.url);
const unroundedUrl = new URL('../src/solver-unrounded.ts', import.meta.url);
const declaration = '\nconst { fround } = Math;\n';
const solverText = readFileSync(solverUrl, 'utf8');
if (!solverText.includes(declaration)) throw new Error('solver.ts no longer declares `const { fround } = Math;`.');
// solver.ts opens with a paragraph saying that it rounds, which the generated file must not repeat.
const roundingParagraph = '// The per-particle solver steps. Every operation is rounded to Float32';
const roundingParagraphEnd = solverText.indexOf('\n//\n');
if (!solverText.startsWith(roundingParagraph) || roundingParagraphEnd < 0)
  throw new Error('solver.ts no longer opens with its rounding paragraph followed by a `//` line.');

const unroundedBody = solverText
  .slice(roundingParagraphEnd + '\n//\n'.length)
  .replace(declaration, '\nconst fround = (value: number): number => value;\n')
  // Only bare fround calls: Math.fround and longer names that end in fround keep their rounding.
  .replace(/(?<![\w$.])fround\(/g, '(')
  // The formatter puts trailing commas after multi-line call arguments; a bare group must not keep them.
  .replace(/,(\s*)\)/g, '$1)')
  .replace('\nconst fround = (value: number): number => value;\n', '\n');
const header =
  '// GENERATED by scripts/generate-unrounded-solver.ts from solver.ts. Do not edit.\n' +
  "// The kernels of 'default' precision: the same steps without Float32 rounding, so results are not bit-exact.\n" +
  '//\n';
const generated = header + unroundedBody;

if (process.argv.includes('--check')) {
  if (readFileSync(unroundedUrl, 'utf8') !== generated) {
    console.error('src/solver-unrounded.ts is out of date. Run scripts/generate-unrounded-solver.ts.');
    process.exit(1);
  }
  console.info('src/solver-unrounded.ts is current.');
} else writeFileSync(unroundedUrl, generated);
